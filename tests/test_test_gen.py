"""Phase 4 — assessment test-item generation.

A TEST session (gd_test, interview_test) needs concrete probe items. They are
generated by `generate_test_items(user_id, task_type)`, which reads the learner's
PREP-side weaknesses (via prep_counterpart, mirroring Phase 3.3) and asks the
engine to build items that press exactly there. The call rides the same _local()
dispatch as every other structured call, so it runs offline on qwen.

Fully offline: get_storage and the structured-output call are both patched; no
sqlite, no real model, AI_BACKEND untouched.
"""
import os

import pytest

os.environ.setdefault("GROQ_API_KEY", "test")
os.environ.setdefault("GEMINI_API_KEY", "test")
os.environ.setdefault(
    "SUPABASE_POOLER_URL",
    "postgresql://postgres.ref:pwd@host.pooler.supabase.com:6543/postgres",
)

from app.ai import test_gen as tg  # noqa: E402
from app.ai.test_gen import ProbeItem, ProbeSet, generate_test_items  # noqa: E402
from app.content.skills import SkillID  # noqa: E402
from app.content.task_types import TaskType  # noqa: E402

pytestmark = pytest.mark.asyncio

_PREP_WEAKNESS = {
    "user_id": "u1",
    "task_type": TaskType.GD_PREP.value,
    "skill_id": SkillID.GD_STANCE_CLARITY.value,
    "hit_count": 3,
    "last_score": 0.3,
    "last_seen": 1.0,
    "last_raw": "rambled without taking a clear stance",
}


class _FakeStore:
    def __init__(self, by_task_type):
        self._by = by_task_type
        self.queried: list[str] = []

    async def get_weaknesses(self, user_id, task_type=None):
        self.queried.append(task_type)
        return list(self._by.get(task_type, []))


def _patch_ai(monkeypatch, store, returns):
    """Patch storage + the local structured call; record the prompt sent."""
    captured = {}

    async def _fake_structured(prompt, schema_cls):
        captured["prompt"] = prompt
        captured["schema"] = schema_cls
        return returns

    monkeypatch.setattr(tg, "get_storage", lambda: store)
    monkeypatch.setattr(tg, "ollama_structured", _fake_structured)
    monkeypatch.setattr(tg, "_local", lambda: True)
    return captured


async def test_generated_items_validate_schema(monkeypatch):
    items = ProbeSet(
        items=[
            ProbeItem(
                skill_id=SkillID.GD_STANCE_CLARITY.value,
                prompt="Should social media be regulated? State your stance first.",
                aim="Opens with a clear, committed position.",
            ),
            ProbeItem(
                skill_id=SkillID.GD_REBUTTAL.value,
                prompt="Respond to: 'regulation kills innovation'.",
                aim="Directly rebuts the prior point.",
            ),
        ]
    )
    store = _FakeStore({TaskType.GD_PREP.value: [_PREP_WEAKNESS]})
    _patch_ai(monkeypatch, store, items)

    result = await generate_test_items("u1", TaskType.GD_TEST.value)

    assert isinstance(result, list)
    assert len(result) == 2
    assert all(isinstance(it, ProbeItem) for it in result)
    assert all(it.skill_id and it.prompt for it in result)


async def test_test_gen_targets_logged_weakness(monkeypatch):
    items = ProbeSet(
        items=[
            ProbeItem(
                skill_id=SkillID.GD_STANCE_CLARITY.value,
                prompt="x",
                aim="y",
            )
        ]
    )
    store = _FakeStore({TaskType.GD_PREP.value: [_PREP_WEAKNESS]})
    captured = _patch_ai(monkeypatch, store, items)

    await generate_test_items("u1", TaskType.GD_TEST.value)

    # reads the PREP sibling, not the (empty) test task type
    assert TaskType.GD_PREP.value in store.queried
    # the weakness is folded into the generation prompt verbatim
    assert SkillID.GD_STANCE_CLARITY.value in captured["prompt"]
    assert "rambled without taking a clear stance" in captured["prompt"]
    assert captured["schema"] is ProbeSet


async def test_empty_ai_result_falls_back(monkeypatch):
    store = _FakeStore({TaskType.GD_PREP.value: [_PREP_WEAKNESS]})
    _patch_ai(monkeypatch, store, ProbeSet(items=[]))

    result = await generate_test_items("u1", TaskType.GD_TEST.value)

    # never hand a TEST session an empty roster — deterministic fallback fills in
    assert isinstance(result, list)
    assert len(result) >= 1
    assert all(isinstance(it, ProbeItem) for it in result)
    assert all(it.skill_id and it.prompt for it in result)


async def test_no_history_still_generates(monkeypatch):
    items = ProbeSet(
        items=[
            ProbeItem(
                skill_id=SkillID.ANSWER_RELEVANCE.value,
                prompt="Tell me about a time you led a team.",
                aim="Stays on the asked question.",
            )
        ]
    )
    store = _FakeStore({})  # learner never coached prep -> no weaknesses
    captured = _patch_ai(monkeypatch, store, items)

    result = await generate_test_items("u1", TaskType.INTERVIEW_TEST.value)

    assert TaskType.INTERVIEW_PREP.value in store.queried
    assert len(result) == 1
    # generic prompt path: still asks for items, just no weakness probe line
    assert "weakness" not in captured["prompt"].lower()
